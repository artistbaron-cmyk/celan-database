def read_csv(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def prompt_for(row):
    word = row["headword"]
    ident = row["id"]
    if ident in PROMPT_OVERRIDES:
        return PROMPT_OVERRIDES[ident]
    if ident == "i":
        return "-ee"
    if word.startswith("-") or word.endswith("-"):
        return word.strip("-")
    if "aen" in word.casefold():
        raise ValueError(f"Needs a reviewed no-H speech prompt: {ident} {word}")
    if "x" in word.casefold():
        raise ValueError(f"Needs a reviewed KS speech prompt: {ident} {word}")
    return word


def select(count):
    assert 1 <= count <= 200
    manifests = sorted(AUDIO.glob("volume_???/manifest.csv"))
    existing = [row for manifest in manifests for row in read_csv(manifest)]
    existing_ids = {row["headword_id"] for row in existing}
    existing_words = {row["headword"].strip().casefold() for row in existing}
    current = AUDIO / (manifests[-1].parent.name if manifests else "volume_001")
    room = 200 - len(list(current.glob("*.mp3")))
    if room == 0:
        current = AUDIO / f"volume_{int(current.name.split('_')[1]) + 1:03}"
        room = 200 - len(list(current.glob("*.mp3")))
    assert room >= count, f"Only {room} slots remain in {current.name}"
    chosen = []
    for row in read_csv(ENTRIES):
        ident, word = row["id"], row["headword"]
        if ident in existing_ids or word.strip().casefold() in existing_words:
            continue
        safe_word = word.rstrip("!?").replace(" / ", " or ")
        safe_ident = ident.replace(" / ", "__")
        assert "/" not in safe_word and "\\" not in safe_word
        assert "/" not in safe_ident and "\\" not in safe_ident
        chosen.append({
            "headword_id": ident,
            "headword": word,
            "dictionary_pronunciation": row["pronunciation"],
            "source_entry_ids": row["source_entry_ids"],
            "generation_prompt": prompt_for(row),
            "audio_file": f"HW-{safe_ident} - {safe_word}.mp3",
            "volume": current.name,
        })
        if len(chosen) == count:
            break
    return chosen


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--count", type=int, default=30)
    args = parser.parse_args()
    print(json.dumps(select(args.count), ensure_ascii=False))
