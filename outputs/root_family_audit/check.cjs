const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const read = f => fs.readFileSync(path.join(__dirname,f),'utf8');
const coverage = JSON.parse(read('coverage.json'));
const findings = JSON.parse(read('findings.json'));
const snapshot = JSON.parse(read('snapshot.json'));
assert.equal(coverage.length,1496);
assert.equal(new Set(coverage.map(r=>r.id)).size,1496);
assert.deepEqual(snapshot.embeddedMismatches,[]);
for (const row of coverage) for (const id of row.flags) assert.ok(findings.some(f=>f.id===id));
assert.ok(findings.find(f=>f.id==='RF01').records.some(r=>r.term==='-ka'));
assert.ok(findings.find(f=>f.id==='RF01').records.some(r=>r.term==='-esh'));
assert.ok(findings.find(f=>f.id==='RF04').records.some(r=>r.term==='Velkrel'));
for (const term of ['Em','Varin']) assert.equal(snapshot.entries.find(g=>g.term===term).family.relatedEntries.length,0);
const els = new Map();
const el = selector => { if(!els.has(selector)) els.set(selector,{value:'',textContent:'',innerHTML:'',listeners:{},dataset:{},addEventListener(n,fn){this.listeners[n]=fn},click(){}}); return els.get(selector); };
const storage = new Map();
const ctx=vm.createContext({console,document:{querySelector:el,createElement:()=>({click(){}})},localStorage:{getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)}});
vm.runInContext(read('review.html').split('<script>')[1].split('</script>')[0],ctx);
assert.match(el('#stats').textContent,/1,496/);
assert.match(el('#issues').innerHTML,/RF11/);
el('#search').value='Velkrel';el('#search').listeners.input();
assert.match(el('#coverage').innerHTML,/Velkrel/);
assert.doesNotMatch(el('#coverage').innerHTML,/>Serilin</);
el('#issues').listeners.input({target:{dataset:{id:'RF04',field:'notes'},value:'Show the recorded base word.'}});
assert.match(storage.get('celan-root-family-audit-v1'),/Show the recorded base word/);
el('#issues').listeners.input({target:{dataset:{id:'RF04',field:'decision'},value:'Approve with my notes'}});
el('#search').listeners.input();
assert.match(el('#issues').innerHTML,/selected>Approve with my notes/);
console.log('PASS: all-headword coverage, embedded-data parity, concrete finding evidence, protected independent words, report rendering, search, and saved review decisions.');
